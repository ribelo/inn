(* Generates the embedded guide catalog for lib/docs.ml from the Markdown
   files under docs/guides. One dune rule invokes this, so the guides are
   compiled into the binary and the server never reads a checkout path at run
   time (desc-bqwh).

   Usage: gen_docs NAME:PATH ... *)

let read_file path =
  let channel = open_in_bin path in
  Fun.protect
    ~finally:(fun () -> close_in_noerr channel)
    (fun () -> really_input_string channel (in_channel_length channel))

(* The title is the first Markdown heading, so a guide owns its own title. *)
let title_of content =
  let first_line =
    match String.index_opt content '\n' with
    | None -> content
    | Some index -> String.sub content 0 index
  in
  let line = String.trim first_line in
  if String.length line > 2 && String.starts_with ~prefix:"# " line then
    String.trim (String.sub line 2 (String.length line - 2))
  else line

let split_arg arg =
  match String.index_opt arg ':' with
  | Some index when index > 0 && index < String.length arg - 1 ->
      ( String.sub arg 0 index,
        String.sub arg (index + 1) (String.length arg - index - 1) )
  | _ -> failwith ("expected NAME:PATH, got " ^ arg)

let () =
  let args = match Array.to_list Sys.argv with [] -> [] | _ :: rest -> rest in
  if args = [] then failwith "expected at least one NAME:PATH argument";
  print_string "(* Generated by tools/gen_docs from docs/guides. Do not edit. *)\n\n";
  print_string "let guides : (string * string * string) list =\n  [\n";
  List.iter
    (fun arg ->
      let name, path = split_arg arg in
      let content = read_file path in
      Printf.printf "    (%S, %S, %S);\n" name (title_of content) content)
    args;
  print_string "  ]\n"
